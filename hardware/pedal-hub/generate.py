"""TLTR pedal hub: RP2040-Zero carrier with two 6.35 mm footswitch jacks.

Matches pedals/rp2040-dual-pedal-hid: pedal 1 tip -> GP14, pedal 2 tip ->
GP15, sleeves -> GND, internal pull-ups, active low. Each input gets a 330 R
series resistor and a 100 nF cap to ground. The pedal cables are long, unshielded
antennas; the RC (33 us) blunts ESD and RF pickup without touching the
firmware's 25 ms debounce. Ring is grounded too, so both TS plugs and TRS
pedals that switch tip-to-ring work.

Regenerate:  scripts/kicad python3 hardware/pedal-hub/generate.py [--export]
"""

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from kigen.build import main  # noqa: E402
from kigen.design import Design, Part, Text, Track, Zone  # noqa: E402
from kigen.libs import module_footprint, module_symbol  # noqa: E402

## Mechanical constants (mm). Board origin = top-left; the back edge (y=0)
## carries the USB-C port and both jacks.
W, H = 82.0, 46.0
PITCH = 2.54
ROW_GAP = 15.24  # RP2040-Zero side rows; from Waveshare-derived community footprint, verify with calipers
MODULE = (41.0, 11.75)  # centre: 23.5 mm module, USB edge flush with the board edge
JACK_Y = 16.67  # puts the NMJ6HCD2 body front (local x=16.67) on the board edge
JACK1_X, JACK2_X = 10.5, 55.27
JACK_AXIS_OFFSET = 8.115  # plug axis is midway between the pad rows (local y=8.115)
TRACK = 0.4

## RP2040-Zero, top view, USB up. Left column top->bottom, right column top->bottom.
RP_LEFT = [("23", "5V"), ("22", "GND"), ("21", "3V3"), ("20", "GP29"), ("19", "GP28"),
           ("18", "GP27"), ("17", "GP26"), ("16", "GP15"), ("15", "GP14")]
RP_RIGHT = [(str(i + 1), f"GP{i}") for i in range(9)]

JACK_FP = "Connector_Audio:Jack_6.35mm_Neutrik_NMJ6HCD2_Horizontal"
R_FP = "Resistor_THT:R_Axial_DIN0207_L6.3mm_D2.5mm_P7.62mm_Horizontal"
C_FP = "Capacitor_THT:C_Disc_D3.0mm_W1.6mm_P2.50mm"
HOLE_FP = "MountingHole:MountingHole_3.2mm_M3"


def build() -> Design:
    d = Design(
        name="pedal-hub",
        title="TLTR pedal hub",
        revision="1",
        board_size=(W, H),
        comments=["RP2040-Zero + 2x 6.35 mm footswitch jacks",
                  "Firmware: pedals/rp2040-dual-pedal-hid (GP14 / GP15, active low)",
                  "Generated by hardware/pedal-hub/generate.py; edit the generator, not this file"],
    )
    d.custom_symbols["TLTR:RP2040-Zero"] = module_symbol(
        "TLTR:RP2040-Zero", RP_LEFT, RP_RIGHT, "TLTR:RP2040-Zero_TH",
        "Waveshare RP2040-Zero on 2.54 mm pin headers (side rows only)")
    d.custom_footprints["TLTR:RP2040-Zero_TH"] = module_footprint(
        "RP2040-Zero_TH", (18.0, 23.5),
        [(-ROW_GAP / 2, [n for n, _ in RP_LEFT]), (ROW_GAP / 2, [n for n, _ in RP_RIGHT])],
        PITCH, "Waveshare RP2040-Zero, side rows on pin headers, rows 15.24 mm apart; bottom row unused")

    rp_pins = {"22": "GND", "16": "GP15", "15": "GP14"}
    d.parts += [
        Part("U1", "TLTR:RP2040-Zero", "RP2040-Zero", "TLTR:RP2040-Zero_TH", rp_pins,
             sch=(152.4, 88.9), pcb=(*MODULE, 0),
             fields={"MPN": "Waveshare RP2040-Zero (SKU 20187)"}),
    ]
    for i, (jx, gp) in enumerate(((JACK1_X, "GP14"), (JACK2_X, "GP15")), start=1):
        tip = f"PEDAL{i}_TIP"
        sy = 60.96 + (i - 1) * 50.8
        right = i == 2
        rx = jx if not right else jx  # R pad 1 sits under the jack tip pad
        d.parts += [
            Part(f"J{i}", "Connector_Audio:AudioJack3_Switch", f"Pedal {i}", JACK_FP,
                 {"T": tip, "R": "GND", "S": "GND"}, sch=(50.8, sy), pcb=(jx, JACK_Y, 90),
                 fields={"MPN": "Neutrik NMJ6HCD2"}),
            Part(f"R{i}", "Device:R", "330", R_FP, {"1": tip, "2": gp},
                 sch=(76.2, sy - 2.54), pcb=(rx, 30.0, 180 if right else 0)),
            Part(f"C{i}", "Device:C", "100n", C_FP, {"1": gp, "2": "GND"},
                 sch=(91.44, sy - 2.54), pcb=(rx + (-7.62 if right else 7.62), 34.0, 180 if right else 0)),
        ]
    for i, (hx, hy) in enumerate(((4, 4), (W - 4, 4), (4, H - 4), (W - 4, H - 4)), start=1):
        d.parts.append(Part(f"H{i}", "Mechanical:MountingHole", "M3", HOLE_FP, {},
                            sch=(190.5 + (i - 1) * 12.7, 139.7), pcb=(hx, hy, 0), in_bom=False))

    ## Routing: signals on B.Cu, F.Cu left as an unbroken ground plane.
    gp14 = (MODULE[0] - ROW_GAP / 2, MODULE[1] + 4 * PITCH)
    gp15 = (MODULE[0] - ROW_GAP / 2, MODULE[1] + 3 * PITCH)
    r1b = (JACK1_X + 7.62, 30.0)
    r2b = (JACK2_X - 7.62, 30.0)
    d.tracks += [
        Track("PEDAL1_TIP", [(JACK1_X, JACK_Y), (JACK1_X, 30.0)], TRACK),
        Track("PEDAL2_TIP", [(JACK2_X, JACK_Y), (JACK2_X, 30.0)], TRACK),
        Track("GP14", [r1b, (r1b[0], 34.0)], TRACK),
        Track("GP15", [r2b, (r2b[0], 34.0)], TRACK),
        # 45-degree legs land exactly on the header pads
        Track("GP14", [r1b, (gp14[0] - (30.0 - gp14[1]), 30.0), gp14], TRACK),
        Track("GP15", [r2b, (gp15[0] + (30.0 - gp15[1]), 30.0), gp15], TRACK),
    ]
    d.zones += [Zone("GND", "F.Cu"), Zone("GND", "B.Cu")]
    d.texts += [
        Text("TLTR pedal hub r1", (W / 2, H - 4), size=1.5),
        Text("P1 / GP14", (JACK1_X + JACK_AXIS_OFFSET, 25.6), size=1.0),
        Text("P2 / GP15", (JACK2_X + JACK_AXIS_OFFSET, 25.6), size=1.0),
        Text("github.com/DivitMittal/TLTR", (W / 2, H - 4), layer="B.SilkS", size=1.2),
    ]

    ## Data for cad/enclosure.py. Heights above the PCB top are estimates from
    ## datasheet drawings, not measurements: check them before printing.
    d.mechanical = {
        "enclosure": {
            "name": "pedal-hub",
            "lid_text": "TLTR",
            "tallest_component_above_pcb": 13.5,  # NMJ6HCD2 body
            "lead_protrusion_below_pcb": 2.0,
            "vents": [],
        },
        "cutouts": [
            {"ref": "U1", "edge": "back", "pos": MODULE[0], "z_above_pcb": 5.1, "shape": "slot",
             "width": 12.5, "height": 7.0,
             "note": "USB-C: 2.5 header plastic + 1.0 module + 1.6 half receptacle; room for a plug overmould"},
            {"ref": "J1", "edge": "back", "pos": JACK1_X + JACK_AXIS_OFFSET, "z_above_pcb": 6.6,
             "shape": "circle", "diameter": 12.1, "note": "NMJ6HCD2 ferrule (~11.5 mm) passes through"},
            {"ref": "J2", "edge": "back", "pos": JACK2_X + JACK_AXIS_OFFSET, "z_above_pcb": 6.6,
             "shape": "circle", "diameter": 12.1, "note": "NMJ6HCD2 ferrule (~11.5 mm) passes through"},
        ],
    }
    return d


if __name__ == "__main__":
    sys.exit(main(build(), HERE))
