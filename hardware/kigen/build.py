"""Generate a full KiCad project from a Design and verify it with kicad-cli."""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path

from .design import Design
from .libs import symbol_library
from .schematic import build_schematic
from .sexpr import dumps

_MAC_CLI = "/Applications/KiCad/KiCad.app/Contents/MacOS/kicad-cli"


def _project_json(design: Design) -> dict:
    return {
        "board": {
            "design_settings": {
                "defaults": {"board_outline_line_width": 0.1, "copper_line_width": 0.2},
                "rules": {
                    "min_clearance": 0.2,
                    "min_track_width": 0.2,
                    "min_via_diameter": 0.6,
                    "min_via_annular_width": 0.13,
                    "min_through_hole_diameter": 0.3,
                    "min_hole_to_hole": 0.25,
                    "min_copper_edge_clearance": 0.5,
                    "min_silk_clearance": 0.0,
                    "min_text_height": 0.8,
                    "min_text_thickness": 0.08,
                },
                "rule_severities": {
                    # Stock footprints are loaded straight from the KiCad
                    # install; the library table check only adds noise when
                    # the board is checked on a machine without global tables.
                    "lib_footprint_issues": "ignore",
                    "lib_footprint_mismatch": "ignore",
                    # Panel connectors (jacks, USB modules) deliberately
                    # overhang the back edge, so their body silkscreen
                    # always crosses Edge.Cuts. Fab houses clip silk anyway.
                    "silk_edge_clearance": "ignore",
                },
            }
        },
        "meta": {"filename": f"{design.name}.kicad_pro", "version": 3},
        "net_settings": {
            "classes": [{
                "name": "Default", "clearance": 0.2, "track_width": 0.3,
                "via_diameter": 0.8, "via_drill": 0.4, "diff_pair_width": 0.2,
                "diff_pair_gap": 0.25, "wire_width": 6, "bus_width": 12,
                "line_style": 0, "schematic_color": "rgba(0, 0, 0, 0.000)",
                "pcb_color": "rgba(0, 0, 0, 0.000)", "priority": 2147483647,
            }],
            "meta": {"version": 4},
        },
        "erc": {"rule_severities": {"lib_symbol_issues": "ignore", "lib_symbol_mismatch": "ignore"}},
        "sheets": [[design.uid("sheet", "root"), "Root"]],
    }


def _lib_tables(design: Design, out: Path) -> None:
    sym_libs = sorted({k.split(":")[0] for k in design.custom_symbols})
    fp_libs = sorted({k.split(":")[0] for k in design.custom_footprints})
    if sym_libs:
        rows = "".join(f'  (lib (name "{n}")(type "KiCad")(uri "${{KIPRJMOD}}/{n}.kicad_sym")(options "")(descr ""))\n'
                       for n in sym_libs)
        (out / "sym-lib-table").write_text(f"(sym_lib_table\n  (version 7)\n{rows})\n")
    if fp_libs:
        rows = "".join(f'  (lib (name "{n}")(type "KiCad")(uri "${{KIPRJMOD}}/{n}.pretty")(options "")(descr ""))\n'
                       for n in fp_libs)
        (out / "fp-lib-table").write_text(f"(fp_lib_table\n  (version 7)\n{rows})\n")
    for lib in sym_libs:
        syms = [s for k, s in sorted(design.custom_symbols.items()) if k.startswith(lib + ":")]
        (out / f"{lib}.kicad_sym").write_text(dumps(symbol_library(syms)) + "\n")
    for key, fp in sorted(design.custom_footprints.items()):
        lib, name = key.split(":", 1)
        (out / f"{lib}.pretty").mkdir(exist_ok=True)
        (out / f"{lib}.pretty" / f"{name}.kicad_mod").write_text(dumps(fp) + "\n")


def _mechanical(design: Design) -> dict:
    w, h = design.board_size
    holes = [{"ref": p.ref, "x": p.pcb[0], "y": p.pcb[1]} for p in design.parts
             if p.pcb is not None and p.footprint.startswith("MountingHole:")]
    return {
        "_comment": "Generated by hardware/kigen from the board design; consumed by the build123d enclosure. "
                    "Board coordinates in mm, origin at the top-left outline corner, +y towards the front.",
        "board": {"width": w, "height": h, "thickness": 1.6, "corner_radius": design.corner_radius},
        "mounting_holes": holes,
        **design.mechanical,
    }


def kicad_cli() -> str:
    found = shutil.which("kicad-cli")
    if found:
        return found
    if Path(_MAC_CLI).exists():
        return _MAC_CLI
    raise FileNotFoundError("kicad-cli not found (run through scripts/kicad)")


def generate(design: Design, out: Path) -> None:
    from .board import build_board  # needs KiCad's pcbnew

    out.mkdir(parents=True, exist_ok=True)
    (out / f"{design.name}.kicad_pro").write_text(json.dumps(_project_json(design), indent=2) + "\n")
    _lib_tables(design, out)
    (out / f"{design.name}.kicad_sch").write_text(build_schematic(design))
    build_board(design, out / f"{design.name}.kicad_pcb")
    (out / "mechanical.json").write_text(json.dumps(_mechanical(design), indent=2) + "\n")


def check(design: Design, out: Path, report_dir: Path) -> bool:
    """ERC and DRC (with schematic parity). Returns True when both are clean."""
    cli = kicad_cli()
    report_dir.mkdir(parents=True, exist_ok=True)
    sch = out / f"{design.name}.kicad_sch"
    pcb = out / f"{design.name}.kicad_pcb"
    erc = subprocess.run([cli, "sch", "erc", "--format", "json", "--severity-all", "--exit-code-violations",
                          "-o", str(report_dir / "erc.json"), str(sch)], capture_output=True, text=True)
    drc = subprocess.run([cli, "pcb", "drc", "--format", "json", "--severity-all", "--schematic-parity",
                          "--exit-code-violations", "-o", str(report_dir / "drc.json"), str(pcb)],
                         capture_output=True, text=True)
    ok = True
    for name, res in (("ERC", erc), ("DRC", drc)):
        status = "clean" if res.returncode == 0 else f"FAILED (exit {res.returncode})"
        print(f"{name}: {status}")
        if res.returncode != 0:
            ok = False
            print(res.stdout[-2000:], res.stderr[-2000:], file=sys.stderr)
    for name in ("erc", "drc"):
        _summarise(report_dir / f"{name}.json")
    return ok


def _summarise(path: Path) -> None:
    if not path.exists():
        return
    data = json.loads(path.read_text())
    items = []
    for sheet in data.get("sheets", []):
        items.extend(sheet.get("violations", []))
    for key in ("violations", "unconnected_items", "schematic_parity"):
        items.extend(data.get(key, []))
    for v in items:
        where = "; ".join(i.get("description", "") for i in v.get("items", []))
        print(f"  [{v.get('severity')}] {v.get('type')}: {v.get('description')} :: {where}")


def export_outputs(design: Design, out: Path) -> None:
    """Schematic PDF, board renders and STEP for review and the enclosure."""
    cli = kicad_cli()
    docs = out / "docs"
    docs.mkdir(exist_ok=True)
    sch = out / f"{design.name}.kicad_sch"
    pcb = out / f"{design.name}.kicad_pcb"
    cmds = [
        [cli, "sch", "export", "pdf", "-o", str(docs / f"{design.name}-schematic.pdf"), str(sch)],
        [cli, "sch", "export", "svg", "-o", str(docs), str(sch)],
        [cli, "pcb", "export", "svg", "--mode-single", "--fit-page-to-board", "--exclude-drawing-sheet",
         "--layers", "Edge.Cuts,F.Cu,F.SilkS,F.Mask", "-o", str(docs / f"{design.name}-top.svg"), str(pcb)],
        [cli, "pcb", "export", "svg", "--mode-single", "--fit-page-to-board", "--exclude-drawing-sheet",
         "--mirror", "--layers", "Edge.Cuts,B.Cu,B.SilkS,B.Mask", "-o", str(docs / f"{design.name}-bottom.svg"),
         str(pcb)],
        [cli, "pcb", "export", "step", "--subst-models", "--force", "-o", str(out / f"{design.name}.step"), str(pcb)],
    ]
    for c in cmds:
        res = subprocess.run(c, capture_output=True, text=True)
        if res.returncode != 0:
            raise RuntimeError(f"{' '.join(c[:4])} failed:\n{res.stdout}\n{res.stderr}")


def main(design: Design, out: Path) -> int:
    """CLI entry used by each board's generate.py."""
    args = set(sys.argv[1:])
    generate(design, out)
    print(f"generated {out}")
    if "--no-check" in args:
        return 0
    ok = check(design, out, out.parent.parent / ".validation" / design.name)
    if ok and "--export" in args:
        export_outputs(design, out)
        print("exported docs/ and STEP")
    return 0 if ok else 1
